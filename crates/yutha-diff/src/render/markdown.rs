#[cfg(test)]
mod tests {
    use super::*;
    use crate::behavioural::{ChainDivergence, ReceiptCountDelta};
    use crate::cedar::CedarPolicyEffect;
    use crate::diff::DIFF_SCHEMA_VERSION;

    fn empty_diff() -> ConstitutionDiff {
        ConstitutionDiff {
            diff_schema_version: DIFF_SCHEMA_VERSION.to_string(),
            left_constitution_version: "1.0.0".into(),
            right_constitution_version: "1.0.0".into(),
            schema_version_change: None,
            cedar_policies: NamedItemsDiff::default(),
            named_predicates: NamedItemsDiff::default(),
            scoring_rules: NamedItemsDiff::default(),
            procedures: NamedItemsDiff::default(),
            enforcement_rules: NamedItemsDiff::default(),
            behavioural: None,
        }
    }

    fn render_to_string(diff: &ConstitutionDiff) -> String {
        let mut buf = Vec::new();
        render(diff, &mut buf).expect("render");
        String::from_utf8(buf).expect("utf8")
    }

    #[test]
    fn empty_diff_shows_no_changes_per_section() {
        let s = render_to_string(&empty_diff());
        // Title with the version transition.
        assert!(s.contains("# Constitution diff (1.0.0 \u{2192} 1.0.0)"));
        // Top-level summary is the single no-changes line.
        assert!(s.contains("## Summary"));
        // All five section headers render even when empty.
        for h in [
            "## Cedar policies",
            "## Named predicates",
            "## Scoring rules",
            "## Procedures",
            "## Enforcement rules",
        ] {
            assert!(s.contains(h), "missing section header {h:?}\n--\n{s}");
        }
        // Behavioural section absent for static-only diffs.
        assert!(
            !s.contains("## Behavioural"),
            "behavioural section MUST be elided for static-only diffs:\n{s}"
        );
    }

    #[test]
    fn added_cedar_policy_renders_inline_source() {
        let mut diff = empty_diff();
        diff.cedar_policies.added.push(CedarPolicyEntry::new(
            "no-x",
            true,
            CedarPolicyEffect::Forbid,
            "@id(\"no-x\")\nforbid (principal, action, resource);",
        ));
        let s = render_to_string(&diff);
        assert!(s.contains("### Added (1)"));
        assert!(s.contains("#### `no-x` (forbid, annotated)"));
        assert!(s.contains("```cedar"));
        assert!(s.contains("@id(\"no-x\")"));
        // Per-section summary count.
        assert!(s.contains("Cedar policies: 1 added, 0 removed, 0 modified"));
    }

    #[test]
    fn unannotated_hint_surfaces_when_present() {
        let mut diff = empty_diff();
        diff.cedar_policies.added.push(CedarPolicyEntry::new(
            "permit:fingerprint",
            false,
            CedarPolicyEffect::Permit,
            "permit (principal, action, resource);",
        ));
        let s = render_to_string(&diff);
        assert!(s.contains("> **Note:** un-annotated Cedar policies"));
        assert!(s.contains("(permit, un-annotated)"));
    }

    #[test]
    fn behavioural_section_renders_when_present() {
        let mut diff = empty_diff();
        diff.behavioural = Some(BehaviouralDiff {
            window_from_unix_ns: 1_000,
            window_to_unix_ns: 2_000,
            replay_session_id: "session-uuid".into(),
            receipt_count_deltas: vec![ReceiptCountDelta {
                action_kind: "constitution.evaluate.deny".into(),
                subject_agent_id: "alice".into(),
                production_count: 12,
                candidate_count: 18,
            }],
            chain_divergences: vec![ChainDivergence {
                target_agent_id: "alice".into(),
                enforcement_rule_id: "forbidden_payload_chain".into(),
                stage: "detect".into(),
                production_count: 0,
                candidate_count: 1,
            }],
        });
        let s = render_to_string(&diff);
        assert!(s.contains("## Behavioural diff (window 1000 \u{2192} 2000)"));
        assert!(s.contains("session-uuid"));
        // Table headers.
        assert!(s.contains("| action_kind | subject_agent_id"));
        assert!(s.contains("| target_agent_id | enforcement_rule_id"));
        // Signed delta formatting.
        assert!(s.contains("+6"));
        assert!(s.contains("+1"));
    }

    #[test]
    fn modified_engine_config_item_renders_before_after() {
        use yutha_cedar_plus::engine_config::NamedPredicate;
        let mut diff = empty_diff();
        diff.named_predicates.modified.push(NamedItemChange {
            name: "is_supervisor".into(),
            left: NamedPredicate {
                name: "is_supervisor".into(),
                expr: "principal.role == \"supervisor\"".into(),
            },
            right: NamedPredicate {
                name: "is_supervisor".into(),
                expr: "principal.role == \"admin\"".into(),
            },
        });
        let s = render_to_string(&diff);
        assert!(s.contains("## Named predicates"));
        assert!(s.contains("### Modified (1)"));
        assert!(s.contains("#### `is_supervisor`"));
        assert!(s.contains("**Before:**"));
        assert!(s.contains("**After:**"));
        // The expr string is wrapped in JSON, which escapes the
        // inner quotes around `supervisor` / `admin` to `\"...\"`.
        // Assert on the plain word to avoid coupling to escape
        // shape.
        assert!(s.contains("supervisor"));
        assert!(s.contains("admin"));
    }
}
